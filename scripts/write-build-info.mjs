#!/usr/bin/env node
// Stamps the commit being built into the Worker bundle so /api/health can
// report which code is actually live. Runs inside `npm run build`, before
// wrangler bundles src/index.js. Workers Builds sets WORKERS_CI_COMMIT_SHA;
// elsewhere fall back to git. The committed copy of src/build-info.js says
// "dev"; a local build rewrites it (restore with `git restore .`).
import { writeFileSync } from 'node:fs';
import { execSync } from 'node:child_process';

let commit = process.env.WORKERS_CI_COMMIT_SHA || '';
if (!commit) {
  try { commit = execSync('git rev-parse HEAD', { stdio: ['ignore', 'pipe', 'ignore'] }).toString().trim(); } catch { commit = 'unknown'; }
}
const branch = process.env.WORKERS_CI_BRANCH || '';
const info = { commit: commit.slice(0, 12), branch, builtAt: new Date().toISOString() };
writeFileSync(new URL('../src/build-info.js', import.meta.url),
  `// Generated by scripts/write-build-info.mjs during \`npm run build\`.\nexport const BUILD = ${JSON.stringify(info)};\n`);
console.log(`Build info: ${info.commit}${branch ? ` (${branch})` : ''}`);
