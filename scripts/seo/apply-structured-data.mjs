/*
 * config/product.json → the site's commerce structured data and feeds.
 *
 *   index.html, odorstrike.html   #org-jsonld, #website-jsonld (+ #product-jsonld on the PDP)
 *   products.json                 JSON Feed catalog (AI agents, shopping crawlers)
 *   merchant-feed.xml             Google Merchant Center product feed (RSS 2.0 + g:)
 *
 * Price, shipping and returns used to be hand-copied into four places and had
 * drifted (handling 0–1 vs 0–2 days, a second Product on a blog post with a
 * different offer URL). Google Merchant Center flags a feed/landing-page
 * mismatch as misrepresentation, so they come from one file now.
 *
 *   node scripts/seo/apply-structured-data.mjs           write
 *   node scripts/seo/apply-structured-data.mjs --check   fail if anything is stale
 */
import { readFileSync, writeFileSync } from 'node:fs';
import {
  getProductConfig, buildProductJsonLd, buildOrganizationJsonLd, buildWebSiteJsonLd,
  buildProductsCatalogFeed,
} from '../product-config.mjs';

const CHECK = process.argv.includes('--check');
const stale = [];

function write(path, next) {
  const prev = readFileSync(path, 'utf8');
  if (prev === next) return;
  stale.push(path);
  if (!CHECK) writeFileSync(path, next);
}

const json = (obj) => JSON.stringify(obj, null, 2);

function stamp(html, id, obj) {
  const re = new RegExp(`(<script type="application/ld\\+json" id="${id}">)[\\s\\S]*?(</script>)`);
  if (!re.test(html)) throw new Error(`apply-structured-data: #${id} not found`);
  // One line: these pages are budgeted to the KB and nobody reads generated JSON.
  return html.replace(re, (_, open, close) => `${open}${JSON.stringify(obj)}${close}`);
}

const xml = (s) => String(s).replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;');

export function buildMerchantFeedXml() {
  const { product: p, brand: b, shipping: s, returns: r } = getProductConfig();
  const [image, ...more] = p.images;
  const item = [
    ['g:id', p.sku],
    ['g:title', p.title],
    ['g:description', p.description.replace(/\*/g, '')],
    ['g:link', p.url],
    ['g:image_link', image],
    ...more.map((u) => ['g:additional_image_link', u]),
    ['g:availability', p.availabilityStatus],
    ['g:price', `${p.price.toFixed(2)} ${p.currency}`],
    ['g:condition', 'new'],
    ['g:brand', b.name],
    ['g:mpn', p.mpn],
    ['g:identifier_exists', 'no'],
    // 6240 = Home & Garden > Household Supplies > Laundry Supplies > Fabric Refreshers
    ['g:google_product_category', '6240'],
    ['g:product_type', xml(p.category)],
    ['g:size', p.size],
    ['g:min_handling_time', s.handlingTimeDays.min],
    ['g:max_handling_time', s.handlingTimeDays.max],
  ];
  const lines = item.map(([k, v]) => `      <${k}>${k === 'g:product_type' ? v : xml(v)}</${k}>`);
  return `<?xml version="1.0" encoding="UTF-8"?>
<!-- GENERATED by scripts/seo/apply-structured-data.mjs from config/product.json — do not hand-edit.
     Google Merchant Center → Products → Add products → From a file → scheduled fetch of
     https://smelloff.in/merchant-feed.xml. Returns (${r.windowDays} days) are set in Merchant Center. -->
<rss version="2.0" xmlns:g="http://base.google.com/ns/1.0">
  <channel>
    <title>${xml(b.name)}</title>
    <link>${b.website}/</link>
    <description>${xml(`${b.name} product feed`)}</description>
    <item>
${lines.join('\n')}
      <g:shipping>
        <g:country>${s.destinationCountry}</g:country>
        <g:service>Standard</g:service>
        <g:price>${s.prepaid.rate.toFixed(2)} ${p.currency}</g:price>
        <g:min_transit_time>${s.transitTimeDays.min}</g:min_transit_time>
        <g:max_transit_time>${s.transitTimeDays.max}</g:max_transit_time>
      </g:shipping>
    </item>
  </channel>
</rss>
`;
}

const org = buildOrganizationJsonLd();
const site = buildWebSiteJsonLd();

let home = readFileSync('index.html', 'utf8');
home = stamp(stamp(home, 'org-jsonld', org), 'website-jsonld', site);
write('index.html', home);

let pdp = readFileSync('odorstrike.html', 'utf8');
pdp = stamp(stamp(stamp(pdp, 'org-jsonld', org), 'website-jsonld', site), 'product-jsonld', buildProductJsonLd());
write('odorstrike.html', pdp);

write('products.json', json(buildProductsCatalogFeed()) + '\n');
write('merchant-feed.xml', buildMerchantFeedXml());

if (CHECK && stale.length) {
  console.error(`apply-structured-data: stale — run node scripts/seo/apply-structured-data.mjs\n  ${stale.join('\n  ')}`);
  process.exit(1);
}
console.log(stale.length ? `apply-structured-data: updated ${stale.join(', ')}` : 'apply-structured-data: up to date');
