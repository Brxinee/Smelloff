#!/usr/bin/env node
/**
 * Stamps per-post share copy into each blog post as meta tags.
 *
 *   node scripts/share/apply-share-templates.mjs           # write
 *   node scripts/share/apply-share-templates.mjs --check   # dry run, exits 1 if stale
 *
 * Source of truth is scripts/share/share-templates.config.mjs. This script only
 * moves that copy into the markup; it never invents any.
 *
 * It replaces the whole marked block on every run rather than patching inside
 * it, so it is idempotent and re-running cannot stack duplicates — the failure
 * mode that killed the retired build-blog-thumbnails.js.
 *
 * A slug present in the markup but missing from the config is not an error:
 * blog-share.js falls back to the page title, which is what every post did
 * before this existed. A slug in the config with no matching post IS an error,
 * because it means copy was written for a page that does not exist.
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { POSTS, validateConfig } from './share-templates.config.mjs';

const HERE = path.dirname(fileURLToPath(import.meta.url));
const REPO = path.resolve(HERE, '..', '..');
const BLOG = path.join(REPO, 'blog');
const CHECK = process.argv.includes('--check');

const OPEN = '<!-- SF-SHARE:COPY — generated by scripts/share/apply-share-templates.mjs. Edit the config, not here. -->';
const CLOSE = '<!-- /SF-SHARE:COPY -->';

const esc = (s) =>
  s.replace(/&/g, '&amp;').replace(/"/g, '&quot;').replace(/</g, '&lt;').replace(/>/g, '&gt;');

function block(t) {
  return [
    OPEN,
    `<meta name="share:whatsapp" content="${esc(t.wa)}">`,
    `<meta name="share:x" content="${esc(t.x)}">`,
    CLOSE,
  ].join('\n');
}

function run() {
  validateConfig();

  const stale = [];
  let stamped = 0;
  let skipped = 0;

  for (const [slug, t] of Object.entries(POSTS)) {
    const file = path.join(BLOG, `${slug}.html`);
    if (!fs.existsSync(file)) {
      throw new Error(`share copy written for "${slug}" but ${file} does not exist`);
    }
    const before = fs.readFileSync(file, 'utf8');

    // Only stamp pages that actually carry the widget — otherwise the meta
    // tags are dead weight on a page with nothing to read them.
    if (!/class="post-share"/.test(before)) {
      skipped++;
      continue;
    }

    // Strip the previous block wholesale, then re-insert. Also clears any
    // hand-written share: tags that were sitting outside the markers.
    let html = before
      .replace(new RegExp(`[ \\t]*${OPEN}[\\s\\S]*?${CLOSE}\\n?`, 'g'), '')
      .replace(/[ \t]*<meta name="share:(?:whatsapp|x|text)"[^>]*>\n?/g, '');

    // Sit them with the other social metadata: right after the Twitter card,
    // which is where a reader looks for anything share-related.
    const anchor = html.lastIndexOf('<meta name="twitter:image:alt"');
    const at =
      anchor !== -1 ? html.indexOf('>', anchor) + 2 : html.lastIndexOf('</head>');
    html = html.slice(0, at) + block(t) + '\n' + html.slice(at);

    if (html !== before) {
      stale.push(`blog/${slug}.html`);
      if (!CHECK) fs.writeFileSync(file, html);
    }
    stamped++;
  }

  console.log(
    `${stamped} post(s) carry share copy` + (skipped ? ` · ${skipped} skipped (no widget)` : '')
  );

  if (stale.length) {
    console.log(`\n${CHECK ? 'stale' : 'updated'} (${stale.length}):`);
    for (const s of stale) console.log('  ' + s);
    if (CHECK) process.exit(1);
  } else {
    console.log('up to date');
  }
}

run();
