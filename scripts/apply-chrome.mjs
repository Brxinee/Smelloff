function ensureSkipTarget(html, override) {
  html = html.replace(/\s*id="sf-main" tabindex="-1"/g, '');

  const from = html.indexOf('<!-- /SF-CHROME:HEADER -->');
  const to = html.indexOf('<!-- SF-CHROME:FOOTER');
  if (from === -1 || to === -1 || to < from) return html;
  const head = html.slice(0, from), body = html.slice(from, to), tail = html.slice(to);

  const candidates = override
    ? [new RegExp(`<([a-z]+)(\\s[^>]*class="${override}"[^>]*)>`)]
    : ['main', 'article', 'section'].map((t) => new RegExp(`<(${t})(\\s[^>]*)?>`));

  for (const re of candidates) {
    const m = body.match(re);
    if (!m) continue;
    return head + body.replace(re, (full, tag, attrs = '') => {
      const cleaned = String(attrs || '').replace(/\s*id="[^"]*"/, '');
      return `<${tag} id="sf-main" tabindex="-1"${cleaned}>`;
    }) + tail;
  }
  return html;
}

let changed = 0, skipped = [];

for (const page of PAGES) {
  const path = join(ROOT, page.file);
  let html;
  try {
    html = readFileSync(path, 'utf8');
  } catch {
    skipped.push(`${page.file} (missing)`);
    continue;
  }
  const before = html;

  html = stripBrokenChromePrefix(html);

  const h = findBlock(html, 'header.sf-hdr') || findBlock(html, page.header);
  if (h) {
    const { start, end } = withMarkers(html, h, 'HEADER');
    html = html.slice(0, start) + header(page.cart) + html.slice(end);
  } else {
    skipped.push(`${page.file} header (${page.header} not found)`);
  }

  const f = findBlock(html, 'footer.sf-ftr') || findBlock(html, page.footer);
  if (f) {
    const marked = withMarkers(html, f, 'FOOTER');
    const start = cutBuy(html, marked.start);
    const insert = (page.buy ? BUY_MODULE + '\n' : '') + FOOTER;
    html = html.slice(0, start) + insert + html.slice(marked.end);
  } else {
    skipped.push(`${page.file} footer (${page.footer} not found)`);
  }

  html = ensureSkipTarget(html, page.skip);
  html = ensureAssets(html);
  html = ensureShareScript(html);
  html = ensureCheckout(html);

  if (html !== before) {
    changed++;
    if (!CHECK) writeFileSync(path, html);
    console.log(`${CHECK ? 'would update' : 'updated'}  ${relative(ROOT, path)}`);
  }
}

if (skipped.length) {
  console.log('\nskipped:');
  for (const s of skipped) console.log('  ' + s);
}
console.log(`\n${changed} page(s) ${CHECK ? 'would change' : 'changed'}.`);
