function stripBrokenChromePrefix(html) {
  const headerAt = html.indexOf('<header class="sf-hdr"');
  if (headerAt === -1) return html;
  const before = html.slice(0, headerAt);
  const markers = (before.match(/<!-- SF-CHROME:HEADER/g) || []).length;
  const skips = (before.match(/<a class="sf-skip"/g) || []).length;
  if (markers <= 1 && skips <= 1) return html;
  const cleaned = before
    .replace(/<!-- SF-CHROME:HEADER[\s\S]*?-->/g, '')
    .replace(/<a class="sf-skip"[^>]*>Skip to content<\/a>/g, '')
    .replace(/<script>window\.SMELLOFF_TRUTH=.*?<\/script>/g, '');
  return cleaned + html.slice(headerAt);
}

function findBlock(html, selector) {
  const [tag, cls] = selector.split('.');
  const openRe = new RegExp(`<${tag}(\\s[^>]*)?>`, 'gi');
  let m;
  while ((m = openRe.exec(html))) {
    const attrs = m[1] || '';
    if (cls) {
      const c = /class\s*=\s*"([^"]*)"/i.exec(attrs);
      if (!c || !c[1].split(/\s+/).includes(cls)) continue;
    }
    const walk = new RegExp(`<(/?)${tag}(\\s[^>]*)?>`, 'gi');
    walk.lastIndex = m.index;
    let depth = 0, w;
    while ((w = walk.exec(html))) {
      depth += w[1] === '/' ? -1 : 1;
      if (depth === 0) return { start: m.index, end: w.index + w[0].length };
    }
  }
  return null;
}

function withMarkers(html, block, kind) {
  let { start, end } = block;
  const open = `<!-- SF-CHROME:${kind}`;
  const close = `<!-- /SF-CHROME:${kind} -->`;
  const before = html.lastIndexOf(open, start);
  if (before !== -1 && start - before < 800) start = before;
  const after = html.indexOf(close, end);
  if (after !== -1 && after - end < 400) end = after + close.length;
  if (kind === 'HEADER') {
    const skipAt = Math.max(
      html.lastIndexOf('<a class="skip"', start),
      html.lastIndexOf('<a class="sf-skip"', start),
      html.lastIndexOf('<a href="#content" class="skip-link"', start),
    );
    if (skipAt !== -1 && start - skipAt < 160) start = skipAt;
  }
  return { start, end };
}

function cutBuy(html, footerStart) {
  const open = html.lastIndexOf('<!-- SF-CHROME:BUY', footerStart);
  if (open !== -1 && footerStart - open < 8000) return open;
  return footerStart;
}

function ensureHreflangHead(headHtml) {
  const can = (headHtml.match(/<link[^>]+rel=["']canonical["'][^>]+href=["']([^"']+)/i) || [])[1];
  if (!can || /noindex/i.test(headHtml)) return headHtml;
  const tags = `  <link rel="alternate" hreflang="en-IN" href="${can}">\n  <link rel="alternate" hreflang="x-default" href="${can}">`;
  let out = headHtml.replace(/\s*<link rel="alternate" hreflang="[^"]+" href="[^"]*"\s*\/?>/gi, '');
  if (/rel=["']canonical["']/i.test(out)) {
    out = out.replace(/(<link[^>]+rel=["']canonical["'][^>]*>)/i, `$1\n${tags}`);
  }
  return out;
}

